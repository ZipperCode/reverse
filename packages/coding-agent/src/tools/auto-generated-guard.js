import { editAutoGeneratedMessage } from "@rva/natives";
import { settings as globalSettings, isSettingsInitialized } from "../config/settings";
import { ToolError } from "@rva/tui/tools/tool-errors";
import { cfgEditBlockAutoGenerated } from "../edit/settings";
function shouldBlockAutoGeneratedFiles(activeSettings) {
    if (activeSettings)
        return cfgEditBlockAutoGenerated.get(activeSettings);
    if (isSettingsInitialized())
        return cfgEditBlockAutoGenerated.get(globalSettings);
    return cfgEditBlockAutoGenerated.default;
}
/** Throw when the native generated-file detector rejects this path. */
export async function assertEditableFile(absolutePath, displayPath, activeSettings) {
    if (!shouldBlockAutoGeneratedFiles(activeSettings))
        return;
    const message = editAutoGeneratedMessage(absolutePath, displayPath ?? absolutePath);
    if (message)
        throw new ToolError(message);
}
